import PDFDocument from 'pdfkit'

const clean=value=>String(value||'').replace(/\s+/g,' ').trim()
const list=value=>Array.isArray(value)?value.map(clean).filter(Boolean):[]

export async function buildDailyDevotionPdf(plan){
  const devotion=plan?.spiritual||{}
  const doc=new PDFDocument({size:'LETTER',margins:{top:58,bottom:62,left:62,right:62},info:{Title:`Church Triumphant Daily Devotion — ${plan?.date||''}`,Author:'Church Triumphant'}})
  const chunks=[]
  doc.on('data',chunk=>chunks.push(chunk))
  doc.fillColor('#9B783E').font('Helvetica-Bold').fontSize(10).text('CHURCH TRIUMPHANT',{align:'center',characterSpacing:1.5})
  doc.moveDown(.7).fillColor('#25231F').font('Helvetica-Bold').fontSize(24).text('Daily Devotion',{align:'center'})
  doc.moveDown(.35).fillColor('#77726A').font('Helvetica').fontSize(11).text(clean(plan?.date),{align:'center'})
  const heading=(title)=>{doc.moveDown(1.2).fillColor('#9B783E').font('Helvetica-Bold').fontSize(12).text(title.toUpperCase());doc.moveDown(.35)}
  heading('Scripture')
  const scripture=list(devotion.scripture)
  doc.fillColor('#25231F').font('Helvetica').fontSize(11).text(scripture.length?scripture.join(' · '):'Scripture focus awaiting confirmation.',{lineGap:4})
  heading('Devotion Focus')
  doc.fillColor('#25231F').font('Helvetica').fontSize(11).text(clean(devotion.devotionFocus)||'Devotion focus awaiting confirmation.',{lineGap:4})
  const bullets=(title,items)=>{heading(title);const values=list(items);if(!values.length){doc.fillColor('#25231F').font('Helvetica').fontSize(11).text('Awaiting confirmation.');return}values.forEach(item=>{doc.fillColor('#25231F').font('Helvetica').fontSize(11).text(`•  ${item}`,{indent:6,lineGap:4});doc.moveDown(.25)})}
  bullets('Prayer Focus',devotion.prayerFocus)
  bullets('Family Discussion',devotion.discussionPrompts)
  heading('Obedience Action')
  doc.fillColor('#25231F').font('Helvetica').fontSize(11).text(clean(devotion.obedienceAction)||'Obedience action awaiting confirmation.',{lineGap:4})
  heading('Required Output')
  doc.fillColor('#25231F').font('Helvetica').fontSize(11).text(clean(devotion.requiredOutput)||'Required output awaiting confirmation.',{lineGap:4})
  doc.moveDown(1.5).strokeColor('#C5A46D').lineWidth(.6).moveTo(62,doc.y).lineTo(550,doc.y).stroke()
  doc.moveDown(.7).fillColor('#77726A').font('Helvetica-Oblique').fontSize(9).text('Generated by Brevity from the active Church Triumphant sermon source.',{align:'center'})
  doc.end()
  await new Promise((resolve,reject)=>{doc.on('end',resolve);doc.on('error',reject)})
  return Buffer.concat(chunks)
}
